// Run via AM_BROWSER_TEST=1 PHP=... python3 server/tests/panel_test.py.
// Playwright is optional; AM_PLAYWRIGHT_MODULE can point to a local installation.
const { chromium } = require(process.env.AM_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport:{width:1280,height:960}});
    const errors=[];
    page.on('pageerror', error=>errors.push(error.message));
    await page.goto(process.argv[2]+'/fixture.php?user=1&many=1');
    await page.goto(process.argv[2]+'/am-app/#pricing');
    assert.equal(await page.locator('[data-am-section]:visible').count(),1);
    assert.equal(await page.locator('.am-package').count(),12);
    await page.locator('.am-package summary').first().click();
    assert.equal(await page.locator('.am-price:visible').count(),1);
    await page.locator('input[name=q]').fill('Package 20');
    await page.getByRole('button',{name:'Apply filters',exact:true}).click();
    assert.equal(await page.locator('.am-package').count(),1);
    await page.locator('.am-package summary').click();
    await page.locator('.am-price input[name=amount]').fill('15.75');
    await page.getByRole('button',{name:'Save package price',exact:true}).click();
    assert.equal(await page.locator('input[name=q]').inputValue(),'Package 20');
    assert.match(await page.locator('.am-package summary').innerText(),/15.75 CAD/);
    await page.locator('[data-am-link=settings]').click();
    await page.locator('#settings input[name=display_name]').fill('Unsaved name');
    await page.locator('[data-am-link=square]').click();
    assert.equal(await page.locator('#square').isVisible(),true);
    await page.goBack();
    assert.equal(await page.locator('#settings input[name=display_name]').inputValue(),'Unsaved name');
    await page.getByRole('link',{name:'Packages & prices',exact:true}).click();
    await page.getByRole('link',{name:'Clear filters',exact:true}).click();
    await page.getByRole('link',{name:'Next →',exact:true}).click();
    assert.match(await page.locator('.am-pager').innerText(),/Page 2 of 4/);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await page.locator('.am-nav a').evaluateAll(links=>links.every(link=>link.getBoundingClientRect().width>130)),true);
    // The fixture has no portal stylesheet: provide representative light/dark tokens for visual checks.
    await page.addStyleTag({content:`:root{--text:#172033;--text-muted:#607087;--card:#fff;--border:#dce2ea;--muted-bg:#f3f5f8;--accent:#8295ed;--bg:#111827}body{margin:0;background:#f3f5f8;font:14px system-ui}.card{border:1px solid var(--border);border-radius:12px;background:var(--card)}input,select,.btn{box-sizing:border-box;padding:10px;border:1px solid var(--border);border-radius:8px;font:inherit}.btn{text-decoration:none;color:var(--text);background:var(--card)}`});
    await page.screenshot({path:'/tmp/opencode/am-panel-mobile.png',fullPage:true});
    await page.setViewportSize({width:1280,height:960});
    await page.screenshot({path:'/tmp/opencode/am-panel-desktop.png',fullPage:true});
    await page.addStyleTag({content:':root{--text:#e8edf5;--text-muted:#9caac0;--card:#182131;--border:#334057;--muted-bg:#101827}body{background:#101827}'});
    await page.screenshot({path:'/tmp/opencode/am-panel-dark.png',fullPage:true});
    await page.goto(process.argv[2]+'/am-app/?q=Package+20#pricing');
    await page.locator('#pricing .am-package summary').click();
    await page.locator('#pricing input[name=display_name]').fill('Premium <monthly>');
    await page.getByRole('button',{name:'Save package name',exact:true}).click();
    assert.match(await page.locator('#pricing .am-package summary').innerText(),/Customer name: Premium <monthly>/);
    await page.locator('input[name=q]').fill('Premium');
    await page.getByRole('button',{name:'Apply filters',exact:true}).click();
    assert.equal(await page.locator('#pricing .am-package').count(),1);
    await page.locator('#pricing .am-package summary').click();
    await page.locator('#pricing input[name=enabled]').check();
    await page.getByRole('button',{name:'Save package price',exact:true}).click();
    await page.locator('#pricing .am-package summary').click();
    await page.getByRole('link',{name:'Create deal for this package',exact:true}).click();
    assert.equal(await page.locator('#promotions').isVisible(),true);
    await page.locator('#promotions input[name=title]').fill('Weekend <deal>');
    await page.locator('#promotions input[name=amount]').fill('9.50');
    await page.locator('#promotions input[name=description]').fill('A limited-time monthly renewal.');
    await page.locator('#promotions input[type=file]').setInputFiles({name:'banner.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j8N8AAAAASUVORK5CYII=','base64')});
    await page.getByRole('button',{name:'Save promotion',exact:true}).click();
    assert.match(await page.locator('#promotions summary').innerText(),/Weekend <deal>/);
    await page.locator('#promotions .am-package summary').click();
    const image=await page.request.get(new URL(await page.locator('#promotions img').getAttribute('src'),process.argv[2]).toString());
    assert.equal(image.status(),200); assert.equal(image.headers()['content-type'],'image/png');
    await page.getByRole('link',{name:'Edit promotion',exact:true}).click();
    assert.equal(await page.locator('#promotions input[name=amount]').inputValue(),'9.50');
    await page.locator('#promotions input[name=title]').fill('Updated weekend deal');
    await page.getByRole('button',{name:'Save promotion',exact:true}).click();
    await page.locator('#promotions .am-package summary').click();
    await page.getByRole('button',{name:'Disable promotion',exact:true}).click();
    assert.match(await page.locator('#promotions summary').innerText(),/Disabled/,await page.locator('.flash').allTextContents().then(text=>text.join(' ')));
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.deepEqual(errors,[]);
    const noJs=await browser.newPage({javaScriptEnabled:false});
    await noJs.goto(process.argv[2]+'/fixture.php?user=1&many=1');
    await noJs.goto(process.argv[2]+'/am-app/?q=Package+20#pricing');
    assert.equal(await noJs.locator('#pricing .am-package').count(),1);
    await noJs.locator('#pricing .am-package summary').click();
    assert.equal(await noJs.locator('#pricing .am-price').isVisible(),true);
    await page.goto(process.argv[2]+'/fixture.php?user=1&admin=1');
    await page.goto(process.argv[2]+'/am-app/licenses-admin.php');
    const issueForm=page.locator('form:has(input[name=action][value=issue])');
    await issueForm.locator('.reseller-search').fill('missing');
    await page.waitForFunction(()=>document.querySelector('form:has(input[value=issue]) [role=status]').textContent==='0 resellers found.');
    await issueForm.locator('.reseller-search').fill('Alpha');
    await page.waitForFunction(()=>document.querySelector('form:has(input[value=issue]) [role=status]').textContent==='1 resellers found.');
    await issueForm.locator('select[name=reseller_id]').selectOption({label:'Alpha reseller'});
    await issueForm.locator('input[name=replace]').check();
    await issueForm.getByRole('button').click();
    const key=await page.locator('.key').innerText();
    assert.match(key,/^AM-[A-F0-9]{40}$/);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.goto(process.argv[2]+'/fixture.php?user=1');
    await page.goto(process.argv[2]+'/am-app/');
    assert.equal(await page.getByRole('button',{name:'Activate license',exact:true}).count(),1);
    await page.locator('input[name=license_key]').fill(key);
    await page.getByRole('button',{name:'Activate license',exact:true}).click();
    assert.equal(await page.locator('#pricing').isVisible(),true);
    await page.goto(process.argv[2]+'/fixture.php?user=1&admin=1');
    await page.goto(process.argv[2]+'/am-app/licenses-admin.php?reseller=1');
    await page.locator('details').first().locator('summary').click();
    await page.locator('details').first().getByRole('button',{name:'Suspend',exact:true}).click();
    await page.goto(process.argv[2]+'/fixture.php?user=1');
    await page.goto(process.argv[2]+'/am-app/');
    assert.match(await page.locator('main').innerText(),/suspended/i);
    assert.equal(await page.locator('#pricing').count(),0);
    await page.goto(process.argv[2]+'/fixture.php?user=1&admin=1');
    await page.goto(process.argv[2]+'/am-app/licenses-admin.php?reseller=1');
    await page.locator('details').first().locator('summary').click();
    await page.locator('details').first().getByRole('button',{name:'Restore',exact:true}).click();
    console.log('PASS: browser management, promotion flow, mobile/no-JS, license generation/activation/suspension/restoration.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
